const modal = document.getElementById("projectModal");
const modalContent = document.getElementById("modalContent");
const toast = document.getElementById("toast");
let previousFocus = null;
let toastTimer;

function showToast(message) {
  toast.textContent = message;
  toast.classList.add("show");
  clearTimeout(toastTimer);
  toastTimer = setTimeout(() => toast.classList.remove("show"), 2800);
}

function openProject(key, trigger) {
  const project = projectDetails[key];
  if (!project) return;
  previousFocus = trigger;
  const blocks = project.blocks.map(([heading, content]) => {
    const body = Array.isArray(content)
      ? `<ul>${content.map(item => `<li>${item}</li>`).join("")}</ul>`
      : `<p>${content}</p>`;
    return `<article class="detail-block"><h3>${heading}</h3>${body}</article>`;
  }).join("");
  modalContent.innerHTML = `
    <span class="modal-index">${project.number}</span>
    <h2 id="modalTitle">${project.title}</h2>
    <p class="modal-summary">${project.summary}</p>
    <div class="detail-grid">${blocks}</div>
    <div class="evidence-area">
      <h3>PROJECT EVIDENCE / ADD YOUR VERIFIED MATERIAL</h3>
      <div class="evidence-links">
        <button data-placeholder="Add a public GitHub repository URL">GitHub repository ↗</button>
        <button data-placeholder="Add sanitized screenshots">Screenshots</button>
        <button data-placeholder="Add a technical write-up URL">Write-up</button>
        <button data-placeholder="Add a demo URL, if applicable">Demo</button>
        <button data-placeholder="Add technical documentation URL">Documentation</button>
      </div>
      <p class="small-note">Evidence links are placeholders because no public project URLs or approved screenshots were supplied. Only publish sanitized, authorized material.</p>
    </div>`;
  modal.classList.add("open");
  modal.setAttribute("aria-hidden", "false");
  document.body.style.overflow = "hidden";
  modal.querySelector(".modal-close").focus();
}

function closeModal() {
  modal.classList.remove("open");
  modal.setAttribute("aria-hidden", "true");
  document.body.style.overflow = "";
  if (previousFocus) previousFocus.focus();
}

document.querySelectorAll(".project-card").forEach(card => {
  card.addEventListener("click", () => openProject(card.dataset.project, card));
});
modal.addEventListener("click", event => {
  if (event.target.matches("[data-close-modal]")) closeModal();
  const placeholder = event.target.closest("[data-placeholder]");
  if (placeholder) showToast(placeholder.dataset.placeholder);
});
document.addEventListener("keydown", event => {
  if (event.key === "Escape" && modal.classList.contains("open")) closeModal();
});

document.querySelectorAll("[data-placeholder]").forEach(element => {
  if (element.closest("#projectModal")) return;
  element.addEventListener("click", event => {
    if (element.tagName === "A" && element.getAttribute("href") === "#contact") event.preventDefault();
    if (element.hasAttribute("data-placeholder")) showToast(element.dataset.placeholder);
  });
});

const menuToggle = document.getElementById("menuToggle");
const nav = document.getElementById("nav");
menuToggle.addEventListener("click", () => {
  const isOpen = nav.classList.toggle("open");
  menuToggle.setAttribute("aria-expanded", String(isOpen));
});
nav.querySelectorAll("a").forEach(link => link.addEventListener("click", () => {
  nav.classList.remove("open");
  menuToggle.setAttribute("aria-expanded", "false");
}));

document.getElementById("year").textContent = new Date().getFullYear();

const sections = document.querySelectorAll("main section[id]");
const navLinks = document.querySelectorAll(".nav a[href^='#']");
if ("IntersectionObserver" in window) {
  const observer = new IntersectionObserver(entries => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        navLinks.forEach(link => link.classList.toggle("active", link.getAttribute("href") === `#${entry.target.id}`));
      }
    });
  }, { rootMargin: "-35% 0px -55% 0px" });
  sections.forEach(section => observer.observe(section));
}
